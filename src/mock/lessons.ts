/** 由“小节标题 + 英文/中文句子对”生成带估算时间戳的段落数组 */
function buildParagraphs(
  raw: Array<{ heading: string; lines: Array<[string, string]> }>,
  durations: number[],
  words?: LessonWord[][],
): LessonParagraph[] {
  let t = 0
  let i = 0
  return raw.map((para) => ({
    heading: para.heading,
    sentences: para.lines.map(([text, translation]): LessonSentence => {
      const ws = words ? words[i] : undefined
      let startTime: number
      let endTime: number
      if (ws && ws.length > 0) {
        // 有实测词级时间戳时句边界直接取首词起点→末词终点（含句间停顿）：
        // whisper 量的是最终音频，durations 若是按单句合成时长算的会漏掉停顿，
        // 两套时间打架会导致高亮光标越往后偏得越多（2026-10-29 实测 Greetings 差 15.6s）
        startTime = round2(ws[0].startTime)
        endTime = round2(ws[ws.length - 1].endTime)
        t = endTime
      } else {
        const d = durations[i] ?? 3
        startTime = round2(t)
        endTime = round2(t + d)
        t = endTime
      }
      const s: LessonSentence = { text, translation, startTime, endTime }
      // 单词级时间戳：按全局句子顺序取；缺省时详情页按词长比例估算
      if (ws) s.words = ws
      i++
      return s
    }),
  }))
}

function round2(n: number): number {
  return Math.round(n * 100) / 100
}

